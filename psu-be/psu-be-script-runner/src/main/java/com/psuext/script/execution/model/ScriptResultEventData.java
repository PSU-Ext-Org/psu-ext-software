import com.fasterxml.jackson.annotation.JsonSubTypes;
import com.fasterxml.jackson.annotation.JsonTypeInfo;

/**
 * Marker interface for typed script result event payloads.
 */
@JsonTypeInfo(use = JsonTypeInfo.Id.NAME, include = JsonTypeInfo.As.EXTERNAL_PROPERTY, property = "type")
@JsonSubTypes({
        @JsonSubTypes.Type(value = ScriptLogEventData.class, name = "log"),
        @JsonSubTypes.Type(value = ScriptRecordEventData.class, name = "record")
})
public sealed interface ScriptResultEventData permits ScriptLogEventData, ScriptRecordEventData {
}
