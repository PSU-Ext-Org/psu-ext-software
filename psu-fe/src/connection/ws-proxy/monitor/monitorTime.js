/**
 * Formats a local timestamp for monitor log lines.
 *
 * @param {Date} date
 * @returns {string}
 */
export function formatMonitorTimestamp(date) {
  const year = date.getFullYear();
  const month = pad2(date.getMonth() + 1);
  const day = pad2(date.getDate());
  const hours = pad2(date.getHours());
  const minutes = pad2(date.getMinutes());
  const seconds = pad2(date.getSeconds());
  const milliseconds = String(date.getMilliseconds()).padStart(3, "0");

  return `${year}-${month}-${day} ${hours}:${minutes}:${seconds}.${milliseconds}`;
}

/**
 * Formats a local timestamp for filesystem-friendly monitor log downloads.
 *
 * @param {Date} date
 * @returns {string}
 */
export function formatMonitorDownloadTimestamp(date) {
  const year = date.getFullYear();
  const month = pad2(date.getMonth() + 1);
  const day = pad2(date.getDate());
  const hours = pad2(date.getHours());
  const minutes = pad2(date.getMinutes());
  const seconds = pad2(date.getSeconds());

  return `${year}${month}${day}-${hours}${minutes}${seconds}`;
}

function pad2(value) {
  return String(value).padStart(2, "0");
}
